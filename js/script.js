let savedLang = null;

try {
    savedLang = localStorage.getItem("portfolio-lang");
} catch (error) {
    // Local storage may be unavailable.
}

const browserIsPt = (navigator.language || "")
    .toLowerCase()
    .startsWith("pt");

if (savedLang === "en" || savedLang === "pt") {
    setLanguage(savedLang);
} else {
    setLanguage(browserIsPt ? "pt" : "en");
}


/* =========================================
   11. MOBILE NAVIGATION
========================================= */

function closeMenu() {
    if (!mainNav || !menuToggle) return;

    mainNav.classList.remove("open");
    menuToggle.setAttribute("aria-expanded", "false");

    updateMenuLabel();
}

if (menuToggle && mainNav) {
    menuToggle.addEventListener("click", function () {
        const isOpen = mainNav.classList.toggle("open");

        menuToggle.setAttribute(
            "aria-expanded",
            String(isOpen)
        );

        updateMenuLabel();
    });

    navLinks.forEach(function (link) {
        link.addEventListener("click", closeMenu);
    });

    document.addEventListener("keydown", function (event) {
        if (event.key === "Escape" && mainNav.classList.contains("open")) {
            closeMenu();
            menuToggle.focus();
        }
    });
}


/* =========================================
   12. ACTIVE NAVIGATION
========================================= */

function updateActiveLink() {
    if (currentPage === "index.html") {
        const sections = document.querySelectorAll("main section[id]");
        const scrollPosition = window.scrollY + 160;

        let currentSection = "home";

        sections.forEach(function (section) {
            if (section.offsetTop <= scrollPosition) {
                currentSection = section.id;
            }
        });

        // Check if the user reached the bottom of the page
        const isAtBottom =
            window.innerHeight + window.scrollY >=
            document.documentElement.scrollHeight - 2;

        if (isAtBottom && sections.length > 0) {
            currentSection = sections[sections.length - 1].id;
        }

        navLinks.forEach(function (link) {
            const href = link.getAttribute("href");

            if (!href) return;

            const hash = href.includes("#")
                ? href.split("#")[1]
                : null;

            if (hash && document.getElementById(hash)) {
                const isActive = hash === currentSection;

                link.classList.toggle("active", isActive);

                if (isActive) {
                    link.setAttribute("aria-current", "location");
                } else {
                    link.removeAttribute("aria-current");
                }
            }
        });

        return;
    }

    navLinks.forEach(function (link) {
        const href = link.getAttribute("href");

        const isAbout =
            currentPage === "about.html" && href === "about.html";

        const isContact =
            currentPage === "contact.html" && href === "contact.html";

        if (isAbout || isContact) {
            link.classList.add("active");
            link.setAttribute("aria-current", "page");
        } else if (href === "about.html" || href === "contact.html") {
            link.classList.remove("active");
            link.removeAttribute("aria-current");
        }
    });
}

window.addEventListener("scroll", updateActiveLink, { passive: true });

window.addEventListener("resize", updateActiveLink);

updateActiveLink();


/* =========================================
   13. CONTACT FORM
========================================= */

const contactForm = document.getElementById("contact-form");
const formStatus = document.getElementById("form-status");

if (contactForm && formStatus) {
    contactForm.addEventListener("submit", function (event) {
        event.preventDefault();

        const name = document.getElementById("name").value.trim();
        const email = document.getElementById("email").value.trim();
        const message = document.getElementById("message").value.trim();

        if (!name || !email || !message) {
            formStatus.textContent = currentLang === "pt"
                ? "Preencha todos os campos antes de continuar."
                : "Please complete all fields before continuing.";

            return;
        }

        const subject = encodeURIComponent(
            t("mail_subject") + name
        );

        const body = encodeURIComponent(
            t("mail_name") + ": " + name +
            "\n" + t("mail_email") + ": " + email +
            "\n\n" + t("mail_msg") + ":\n" + message
        );

        formStatus.textContent = t("status_open");

        window.location.href =
            "mailto:" + EMAIL +
            "?subject=" + subject +
            "&body=" + body;
    });
}
