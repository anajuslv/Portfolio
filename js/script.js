/* =========================================
   2. PAGE DETECTION
========================================= */

const currentPage = window.location.pathname
    .split("/")
    .pop() || "index.html";


/* =========================================
   3. LANGUAGE ELEMENTS
========================================= */

const menuToggle = document.getElementById("menu-toggle");
const mainNav = document.getElementById("main-nav");
const navLinks = document.querySelectorAll(".nav-link");

let currentLang = "en";

function t(key) {
    return translations[currentLang][key] ?? "";
}


/* =========================================
   4. TRANSLATE HTML ATTRIBUTES
========================================= */

function translateAttributes() {
    document.querySelectorAll("[data-i18n-attr], [data-i18n-attrs]")
        .forEach(function (element) {

            const attributes =
                element.dataset.i18nAttr ||
                element.dataset.i18nAttrs;

            if (!attributes) return;

            attributes.split(";").forEach(function (item) {
                const parts = item.split(":");
                const attribute = parts[0]?.trim();
                const key = parts[1]?.trim();

                if (attribute && key && t(key)) {
                    element.setAttribute(attribute, t(key));
                }
            });
        });
}


/* =========================================
   5. PAGE TITLE AND META DESCRIPTION
========================================= */

function updatePageMetadata() {
    const pageTitles = translations[currentLang].page_title;

    let pageKey = "index";

    if (currentPage === "about.html") {
        pageKey = "about";
    } else if (currentPage === "contact.html") {
        pageKey = "contact";
    }

    document.title = pageTitles[pageKey];

    const description = document.querySelector(
        'meta[name="description"]'
    );

    if (description) {
        description.setAttribute(
            "content",
            t("meta_description")
        );
    }
}


/* =========================================
   6. CV DOWNLOAD
========================================= */

function updateCVLink() {
    const cvDownload = document.getElementById("cv-download");

    if (!cvDownload) return;

    if (currentLang === "pt") {
        cvDownload.href = "assets/AnaCV-PT.pdf";
    } else {
        cvDownload.href = "assets/AnaCV.pdf";
    }

    cvDownload.setAttribute("download", "");
}


/* =========================================
   7. MOBILE MENU LABEL
========================================= */

function updateMenuLabel() {
    if (!menuToggle || !mainNav) return;

    const isOpen = mainNav.classList.contains("open");

    menuToggle.setAttribute(
        "aria-label",
        isOpen ? t("menu_close") : t("menu_open")
    );
}


/* =========================================
   8. APPLY LANGUAGE
========================================= */

function setLanguage(lang) {
    if (lang !== "en" && lang !== "pt") return;

    currentLang = lang;

    document.documentElement.lang =
        lang === "pt" ? "pt-BR" : "en";

    // Translate text elements
    document.querySelectorAll("[data-i18n]").forEach(function (element) {
        const key = element.dataset.i18n;
        const translation = t(key);

        if (translation !== "") {
            element.innerHTML = translation;
        }
    });

    // Translate placeholders and other attributes
    translateAttributes();

    // Update page title and description
    updatePageMetadata();

    // Update CV download link
    updateCVLink();

    // Update navigation accessibility labels
    if (mainNav) {
        mainNav.setAttribute("aria-label", t("nav_aria"));
    }

    const languageGroup = document.querySelector(".lang-switch");

    if (languageGroup) {
        languageGroup.setAttribute("aria-label", t("lang_label"));
    }

    // Update language buttons
    document.querySelectorAll(".lang-switch button").forEach(function (button) {
        button.setAttribute(
            "aria-pressed",
            button.dataset.lang === lang ? "true" : "false"
        );
    });

    // Update footer and contact accessibility labels
    document.querySelectorAll(".footer-social a").forEach(function (link) {
        const label = link.dataset.i18nAria;

        if (label && t(label)) {
            link.setAttribute("aria-label", t(label));
        }
    });

    updateMenuLabel();

    // Save language preference
    try {
        localStorage.setItem("portfolio-lang", lang);
    } catch (error) {
        // Local storage may be unavailable.
    }
}


/* =========================================
   9. LANGUAGE BUTTONS
========================================= */

document.querySelectorAll(".lang-switch button").forEach(function (button) {
    button.addEventListener("click", function () {
        setLanguage(button.dataset.lang);
    });
});


