function parseAttrs(el) {
    return el.dataset.i18nAttrs.split(";").map(function (pair) {
        return pair.trim().split(":").map(function (part) {
            return part.trim();
        });
    });
}

document.querySelectorAll("[data-i18n-attrs]").forEach(function (el) {
    parseAttrs(el).forEach(function (pair) {
        EN[pair[1]] = el.getAttribute(pair[0]);
    });
});

