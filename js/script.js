function applySpecialTranslations() {
    const timelineItems = document.querySelectorAll(".timeline-item");
    const timelineContent = timelineTranslations[currentLang];

    timelineItems.forEach(function (item, index) {
        const translation = timelineContent[index];
        if (!translation) return;

        const date = item.querySelector(".timeline-date");
        const title = item.querySelector(".timeline-content h3");
        const description = item.querySelector(".timeline-content p:not(.item-subtitle)");

        if (date) date.textContent = translation.date;
        if (title) title.textContent = translation.title;
        if (description) description.textContent = translation.text;
    });

    const projectCards = document.querySelectorAll(".project-card");
    const projectContent = projectTranslations[currentLang];

    projectCards.forEach(function (card, index) {
        const translation = projectContent[index];
        if (!translation) return;

        const title = card.querySelector("h3");
        const description = card.querySelector("p[data-i18n]");

        if (title) title.textContent = translation.title;
        if (description) description.innerHTML = translation.description;
    });
}

/* ==============================
   5. APPLY LANGUAGE
================================= */

function setLanguage(lang) {
    currentLang = lang;
    document.documentElement.lang = lang === "pt" ? "pt-BR" : "en";

    document.querySelectorAll("[data-i18n]").forEach(function (el) {
        const translation = t(el.dataset.i18n);
        if (translation !== "") {
            el.innerHTML = translation;
        }
    });

    document.querySelectorAll("[data-i18n-attrs]").forEach(function (el) {
        parseAttrs(el).forEach(function (pair) {
            const attribute = pair[0];
            const key = pair[1];
            const translation = t(key);

            if (translation !== "") {
                el.setAttribute(attribute, translation);
            }
        });
    });

    applySpecialTranslations();

    document.querySelectorAll(".lang-switch button").forEach(function (button) {
        button.setAttribute(
            "aria-pressed",
            button.dataset.lang === lang ? "true" : "false"
        );
    });

    updateMenuLabel();

    try {
        localStorage.setItem("portfolio-lang", lang);
    } catch (error) {
        // Local storage may be unavailable.
    }
}

document.querySelectorAll(".lang-switch button").forEach(function (button) {
    button.addEventListener("click", function () {
        setLanguage(button.dataset.lang);
    });
});

